// Clean-room `localStorage` custom rainfall station library (`STORAGE_KEYS.customRainDb = 'tramMua'`)

export interface StoredCustomRainRecord {
  ten: string;
  ser: string;
  n: number;
  t: number;
}

export interface CustomRainDbState {
  storageKey: string;
  own: Record<string, 1>;
}

export const TM_DB: CustomRainDbState = {
  storageKey: STORAGE_KEYS.customRainDb,
  own: {},
};

export function tmSlug(s: string): string {
  return (
    String(s)
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/đ/g, "d")
      .replace(/Đ/g, "D")
      .replace(/[^A-Za-z0-9]+/g, "_")
      .replace(/^_|_$/g, "")
      .slice(0, 120) || "tram"
  );
}

export function tmParse(t: string): RainSeriesEntry[] {
  return String(t || "")
    .split(/\r?\n/)
    .map((l) =>
      l
        .trim()
        .replace(/,(?=\d)/g, ".")
        .split(/[\s;\t]+/)
        .map(Number),
    )
    .filter((a) => a.length >= 2 && a.every(Number.isFinite) && a[0] > 1800 && a[0] < 2200 && a[1] > 0)
    .map((a): RainSeriesEntry => [a[0], a[1]]);
}

export function tmLabel(nm: string): void {
  if (typeof document === 'undefined') return;
  const D = HVST[nm];
  if (!D) return;
  const y = D.ser.map((a) => Number(a[0]));
  document.querySelectorAll('#hv_st option, #tvc_st2 option').forEach((o) => {
    const opt = o as HTMLOptionElement;
    if (opt.value === nm) {
      opt.textContent = `${nm} (${Math.min(...y)} - ${Math.max(...y)}, ${D.ser.length} năm)`;
    }
  });
}

function getLocalStorageSafe(): Storage | null {
  try {
    if (typeof window !== 'undefined' && window.localStorage) return window.localStorage;
    if (typeof localStorage !== 'undefined') return localStorage;
  } catch {
    // ignore storage access errors
  }
  return null;
}

function readCustomRainStore(): Record<string, StoredCustomRainRecord> {
  const ls = getLocalStorageSafe();
  if (!ls) return {};
  try {
    const raw = ls.getItem(TM_DB.storageKey);
    if (!raw) return {};
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === 'object' ? (parsed as Record<string, StoredCustomRainRecord>) : {};
  } catch {
    return {};
  }
}

function writeCustomRainStore(store: Record<string, StoredCustomRainRecord>): void {
  const ls = getLocalStorageSafe();
  if (!ls) return;
  try {
    ls.setItem(TM_DB.storageKey, JSON.stringify(store));
  } catch {
    // ignore quota errors
  }
}

export function tmAdd(nm: string, ser: RainSeriesEntry[], note?: string): boolean {
  if (!nm || ser.length < 3) return false;
  if (BUILT_IN_HVST_NAMES.has(nm) && !TM_DB.own[nm]) return false;
  HVST[nm] = {
    tg: "rx",
    ser: ser.map((row) => [...row] as RainSeriesEntry),
    note: note || "Chuỗi mưa nhập bổ sung vào thư viện trạm mưa dùng chung.",
  };
  TM_DB.own[nm] = 1;
  tmLabel(nm);
  return true;
}

export function tmLoadFromStorage(): void {
  const store = readCustomRainStore();
  for (const slug of Object.keys(store)) {
    const o = store[slug];
    if (o && o.ten && !(BUILT_IN_HVST_NAMES.has(o.ten) && !TM_DB.own[o.ten])) {
      tmAdd(o.ten, tmParse(o.ser));
    }
  }
}

export function tmSaveNow(selId: string, taId: string): boolean {
  if (typeof document === 'undefined') return false;
  const s = document.getElementById(selId) as HTMLSelectElement | null;
  const ta = document.getElementById(taId) as HTMLTextAreaElement | null;
  if (!s || !ta) return false;
  const nm = s.value;
  if (!nm || nm === 'khac') return false;
  const D = HVST[nm];
  if (BUILT_IN_HVST_NAMES.has(nm) || (D && !TM_DB.own[nm])) return false;
  const ser = tmParse(ta.value);
  if (ser.length < 3) return false;
  const same = D && JSON.stringify(D.ser) === JSON.stringify(ser);
  tmAdd(nm, ser);
  if (!same) {
    const store = readCustomRainStore();
    store[tmSlug(nm)] = {
      ten: nm,
      ser: ser.map((a) => `${a[0]} ${a[1]}`).join('\n'),
      n: ser.length,
      t: Date.now(),
    };
    writeCustomRainStore(store);
  }
  return true;
}

let tmT: ReturnType<typeof setTimeout> | null = null;
export function tmSave(selId: string, taId: string, delayMs = 1200): void {
  if (tmT !== null) clearTimeout(tmT);
  tmT = setTimeout(() => {
    tmSaveNow(selId, taId);
  }, delayMs);
}

let onWlStepHook: (() => void) | null = null;
let onHvStInfoHook: (() => void) | null = null;

