export function calcFcOf(name?: string | null): number {
  const m = /(\d{3})/.exec(String(name || ''));
  const M = m ? parseInt(m[1], 10) : 300;
  const T = CALC_FCT;
  if (M <= T[0][0]) return T[0][1];
  if (M >= T[T.length - 1][0]) return T[T.length - 1][1];
  for (let i = 1; i < T.length; i++)
    if (M <= T[i][0])
      return T[i - 1][1] + ((T[i][1] - T[i - 1][1]) * (M - T[i - 1][0])) / (T[i][0] - T[i - 1][0]);
  return 25;
}

export function calcFyOf(name?: string | null): number {
  const m = /(\d{3})/.exec(String(name || ''));
  const v = m ? parseInt(m[1], 10) : 400;
  return [300, 400, 500].reduce((a, b) => (Math.abs(b - v) < Math.abs(a - v) ? b : a));
}

