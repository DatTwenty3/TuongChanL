export function calcEnsure(P: EngineProject): CalcConfig {
  if (!P.calc) P.calc = calcDefaults();
  else {
    const c = P.calc as EngineCalcConfig,
      d = calcDefaults();
    if (c.kbx === undefined && (c.kb !== undefined || c.kf !== undefined)) {
      const kb = +(c.kb ?? 0) > 0 ? +(c.kb ?? 0) : 1,
        kf = +(c.kf ?? 0) > 0 ? +(c.kf ?? 0) : 1;
      c.kbx = c.kby = kb * 1e-6;
      c.kfx = c.kfy = kf * 1e-6;
    }
    delete c.kb;
    delete c.kf;
    (Object.keys(d) as (keyof CalcConfig)[]).forEach((k) => {
      if (c[k] === undefined) (c as unknown as Record<string, unknown>)[k] = d[k];
    });
  }
  return P.calc as CalcConfig;
}

export function calcFamilyFix(p: EngineProject, wasD: boolean): void {
  const toD = p.tpl === 'D';
  if (toD === wasD || !p.calc) return;
  const old = p.calc;
  p.calc = toD ? calcDefaultsD() : calcDefaults();
  p.calc.dec = old.dec;
  (['pjName', 'pjItem', 'pjPlace', 'pjBy', 'pjDate'] as const).forEach((k) => {
    if (old[k] !== undefined) p.calc![k] = old[k];
  });
}

