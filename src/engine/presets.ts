export const barA = (d: number, a: number): number => (((Math.PI * d * d) / 4) * 1e3) / (a * 10);

export function calcFindBars(
  cur: { d: number; a: number; n?: number },
  test: (cand: EngineRebarCandidate) => boolean,
): EngineRebarCandidate | null {
  const cands: EngineRebarCandidate[] = [];
  CALC_DS.forEach((d) =>
    CALC_AS.forEach((a) => {
      if (a * 10 - d < Math.max(1.5 * d, 38)) return;
      cands.push({ d, a, As: barA(d, a) });
    }),
  );
  cands.sort(
    (x, y) =>
      x.As - y.As ||
      ((x.a === cur.a) === (y.a === cur.a) ? 0 : x.a === cur.a ? -1 : 1) ||
      x.d - y.d,
  );
  for (const c of cands) if (test(c)) return c;
  return null;
}

