import type { MaterialRecord } from '../types/project';

type RawMaterialSeed = Omit<MaterialRecord, 'index' | 'isGroupHeader' | 'group'> & {
  isGroupHeader?: boolean;
};

function buildMaterialLibrary(groups: Array<{ group: string; items: RawMaterialSeed[] }>): MaterialRecord[] {
  const out: MaterialRecord[] = [];
  let idx = 0;
  for (const g of groups) {
    out.push({
      index: idx++,
      isGroupHeader: true,
      group: g.group,
      name: `(*)${g.group}`,
      E_vong_30C: 0,
      E_truot_60C: 0,
      E_keoUon_10_15C: 0,
      Rku_MPa: 0,
      C_MPa: 0,
      phi_deg: 0,
      note: '',
    });
    for (const item of g.items) {
      out.push({
        index: idx++,
        isGroupHeader: false,
        group: g.group,
        name: item.name,
        E_vong_30C: item.E_vong_30C,
        E_truot_60C: item.E_truot_60C,
        E_keoUon_10_15C: item.E_keoUon_10_15C,
        Rku_MPa: item.Rku_MPa,
        C_MPa: item.C_MPa,
        phi_deg: item.phi_deg,
        note: item.note,
      });
    }
  }
  return out;
}

